//! EscrowLens TEE contract — guest entry point.
//!
//! Mirrors the official Terminal 3 "private customer vault" walkthrough
//! (docs.terminal3.io, write-contract): same `contracts` WIT interface,
//! same tenant-base world (tenant-context + logging + kv-store, no HTTP),
//! same rules — return answers, never values; never log a value; key data
//! by the calling user's DID, never by a DID taken from the input.
//!
//! Functions:
//!   store  — the customer saves their hiring policy (self only).
//!   check  — the customer, or an agent they granted, asks "is this agent
//!            acceptable under my policy?" Gets booleans + score band back.
//!   forget — the customer deletes their policy (self only).
//!
//! The host bindings live under `crate::host::*` and the exported interface
//! under `crate::exports::*` — both generated by wit-bindgen from `wit/`.
//! This module only compiles for wasm32; `cargo test` runs src/logic.rs
//! natively (see tests/logic.rs).

// NOTE: this file is written against the documented T3 contract shape
// (wit-bindgen 0.49, world `escrow-trust`, host interfaces
// host:tenant/tenant-context@2.0.0 + host:interfaces@2.4.0). It has NOT been
// compiled in this sandbox (no Rust toolchain here). Build it with:
//   cargo component build --release --target wasm32-wasip2
// after vendoring wit/deps from github.com/Terminal-3/agent-vault-starter.

// Pure scoring logic — compiled on every target so `cargo test` can run it
// natively (tests/logic.rs imports `escrow_trust::logic`).
pub mod logic;

#[cfg(target_arch = "wasm32")]
mod wasm {
    wit_bindgen::generate!({
        world: "escrow-trust",
        path: "wit",
        generate_all,
    });

    use crate::logic;
    use exports::z::escrow_trust::contracts::{GenericInput, Guest};
    use host::interfaces::{kv_store, logging};
    use host::tenant::tenant_context;
    use serde_json::json;

    const POLICY_MAP_TAIL: &str = "trust-policies";

    // kv-store calls take the FULL map name: z:<hex tenant DID>:<map>.
    fn policy_map() -> String {
        format!("z:{}:{}", hex::encode(tenant_context::tenant_did()), POLICY_MAP_TAIL)
    }

    fn input(req: &GenericInput) -> Result<Vec<u8>, String> {
        req.input.clone().ok_or_else(|| "missing input".to_string())
    }

    fn reply(value: serde_json::Value) -> Result<Vec<u8>, String> {
        serde_json::to_vec(&value).map_err(|e| e.to_string())
    }

    // Only the customer themself may write/delete their policy.
    // Refused on a delegated call: an agent can never overwrite the policy
    // it is being judged against.
    fn self_only_key() -> Result<String, String> {
        if tenant_context::is_delegated() {
            return Err("delegated calls cannot write policies".to_string());
        }
        tenant_context::calling_user_did()
            .map(|did| hex::encode(did))
            .ok_or_else(|| "no calling user DID".to_string())
    }

    fn subject_key() -> Result<String, String> {
        // The record of whoever is being acted for — on an agent's call, the
        // customer who granted it. The agent cannot name anyone else.
        tenant_context::calling_user_did()
            .map(|did| hex::encode(did))
            .ok_or_else(|| "no calling user DID".to_string())
    }

    struct Component;

    impl Guest for Component {
        fn store(req: GenericInput) -> Result<Vec<u8>, String> {
            let key = self_only_key()?;
            let policy: logic::Policy =
                serde_json::from_slice(&input(&req)?).map_err(|e| e.to_string())?;
            if !(0.0..=100.0).contains(&policy.min_score) {
                return Err("min_score must be 0-100".to_string());
            }
            let bytes = serde_json::to_vec(&policy).map_err(|e| e.to_string())?;
            kv_store::put(&policy_map(), key.as_bytes(), &bytes)?;
            logging::info("store: hiring policy saved")?; // never log a value
            reply(json!({ "stored": true, "custom": { "trust_op": "store" } }))
        }

        fn check(req: GenericInput) -> Result<Vec<u8>, String> {
            let key = subject_key()?;
            let args: serde_json::Value =
                serde_json::from_slice(&input(&req)?).map_err(|e| e.to_string())?;
            let agent = args["agent"]
                .as_str()
                .ok_or_else(|| "input.agent must be a string".to_string())?;
            let history: logic::History = serde_json::from_value(args["history"].clone())
                .map_err(|e| e.to_string())?;

            let bytes = kv_store::get(&policy_map(), key.as_bytes())?
                .ok_or_else(|| "no hiring policy stored".to_string())?;
            let policy: logic::Policy =
                serde_json::from_slice(&bytes).map_err(|_| "corrupt policy".to_string())?;

            let eval = logic::evaluate(&policy, agent, &history);
            reply(json!({
                "acceptable": eval.acceptable,
                "score": eval.score,
                "grade": eval.grade,
                "answers": eval.answers,
                // Lifted off the response by the node and stored as labels on
                // this call's activity-log entry.
                "custom": { "trust_op": "check", "acceptable": eval.acceptable.to_string() },
            }))
        }

        fn forget(_req: GenericInput) -> Result<Vec<u8>, String> {
            let key = self_only_key()?;
            let deleted = kv_store::delete(&policy_map(), key.as_bytes())?;
            logging::info("forget: hiring policy deleted")?;
            reply(json!({ "deleted": deleted, "custom": { "trust_op": "forget" } }))
        }
    }

    export!(Component);
}
